#!/usr/bin/env python3
# Writes src/co_pod_sites.h from the reviewed site list of the ship_hellpod manager (game build 25480438):
#   scripts/gen_pod_sites.py <patch_sites_ship_hellpod_optionA.tsv> <game.dll image dump>
# Every row is checked against the dump here, and again by the mod against the running game before it writes.
import struct, sys

MANAGER = 0xEEF968          # the manager inside the component block
# sites that reach the manager from the block: (rva, offset of the disp32 in the instruction)
BLOCK = [(0x556AB2, 3), (0x5670B6, 3), (0x5691BC, 3), (0x56F70B, 3), (0x570671, 2), (0x573C17, 3), (0x580064, 3),
         (0x580091, 2), (0xBD7C45, 3)]
CAPACITY = [0x54AAF8, 0x54AB79, 0x66BFD9, 0x66C095]      # cmp eax,4 (the last two: unreferenced copies)
A1 = (0x88, 0xB8)           # master records, 4 x 0xC
A3 = (0x108, 0x118)         # synced pod state, 4 x 4

tsv, dump = sys.argv[1], open(sys.argv[2], 'rb').read()
rows = []
for rva, at in BLOCK:
    old = struct.unpack_from('<I', dump, rva + at)[0]; assert MANAGER <= old < MANAGER + 0x10, hex(rva)
    rows.append((rva, at, old, 'CO_POD_BLOCK'))
for line in open(tsv).read().splitlines()[1:]:
    c = line.split('\t'); rva, at, raw = int(c[0], 16), int(c[5]), bytes.fromhex(c[6])
    old = struct.unpack_from('<I', raw, at)[0]; assert dump[rva:rva + len(raw)] == raw, hex(rva)
    kind = 'CO_POD_A1' if A1[0] <= old < A1[1] else 'CO_POD_A3' if A3[0] <= old < A3[1] else None
    assert kind and (kind == 'CO_POD_A1') == c[2].startswith('A1'), line
    rows.append((rva, at, old, kind))
for rva in CAPACITY:
    assert dump[rva:rva + 3] == bytes([0x83, 0xF8, 0x04]), hex(rva); rows.append((rva, 2, 4, 'CO_POD_CAPACITY'))
# The ship's pod table (4 x 0x4C at ship+0x11D18): every instruction that addresses it, and the loops over it.
TABLE = [0x65DE8B, 0x65DE93, 0x65DE9F, 0x65DEA7, 0x65DEAF, 0x65DEE6, 0x661AC5, 0x661D92, 0x661E57, 0x661F62, 0x662082,
         0x662EB3, 0x662F58, 0x663261, 0x663321, 0x66B451, 0x66B4C0, 0x66B4C9, 0x66B4D1, 0x66B4DA, 0x66B4E3, 0x11B63C3,
         0x146A687, 0x146A728]
BOUNDS = [(0x66B466, 2), (0x661F7B, 3), (0x66209B, 3), (0x660CDD, 2), (0x146A691, 3), (0x146A70D, 2), (0x65DEFA, 2),
          (0x6632DE, 2), (0x662F3D, 2)]
for rva in TABLE:
    at = [a for a in range(2, 6) if 0x11D18 <= struct.unpack_from('<I', dump, rva + a)[0] < 0x11D18 + 0x4C]
    assert len(at) == 1, hex(rva)
    rows.append((rva, at[0], struct.unpack_from('<I', dump, rva + at[0])[0], 'CO_POD_TABLE'))
for rva, at in BOUNDS:
    assert dump[rva + at] == 4 and dump[rva + at - 1] in (0xF8, 0xF9, 0xFB, 0xFE, 0x7E), hex(rva)
    rows.append((rva, at, 4, 'CO_POD_CAPACITY'))
assert len({r[0] for r in rows}) == len(rows)
out = ['/* Generated by scripts/gen_pod_sites.py from the reviewed site list; do not edit. Game build 25480438. */',
       '#ifndef CO_POD_SITES_H', '#define CO_POD_SITES_H', '',
       '/* {rva, offset of the value in the instruction, its vanilla value, kind, the instruction bytes before it} */',
       'static const CoPodSite kCoPodSites[] = {']
for rva, at, old, kind in sorted(rows):
    pin = ', '.join('0x%02X' % b for b in dump[rva:rva + at])
    out.append('    {0x%Xu, %d, 0x%Xu, %s, {%s}},' % (rva, at, old, kind, pin))
out += ['};', '', '/* The per-pod camera choice (game+0x11BBF97, four fixed names) that the mod replaces. */',
        'static const uint8_t kCoCameraOld[69] = {' + ', '.join('0x%02X' % v for v in dump[0x11BBF97:0x11BBFDC]) + '};', '', '#endif', '']
open(sys.argv[3] if len(sys.argv) > 3 else 'src/co_pod_sites.h', 'w').write('\n'.join(out))
print(len(rows), 'sites')
