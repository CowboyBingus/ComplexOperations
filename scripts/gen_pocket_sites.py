#!/usr/bin/env python3
# Writes src/xl/co_pocket_sites.h: FixUnreachableAreas (0xF67980) and its path search (0xF67210) as the game has them
# and as HellForge's level 11 leaves them (game build 25480438):
#   scripts/gen_pocket_sites.py <game.dll image dump> <HellForge native/mod-loader> [out]
# The three sites the mod writes must be the game's on the dump and named by no source of HellForge's; its restart
# step at 0xF67FDB is the chain's (gen_chain_sites.py). Every frame slot and register the reconnect reads is pinned
# by the instruction that fills it.
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game = open(sys.argv[1], 'rb').read()
stock_dir = sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else HERE + '/../src/xl/co_pocket_sites.h'

SEARCH, ALLOC, CLEAR, RESTART, GO_ON, IN_DISK = 0xF67356, 0xF679C9, 0xF67A0C, 0xF67FDB, 0xF67FB7, 0xF66A90
# site, the game's bytes, the way on
sites = [(SEARCH, '4883BD98000000000F85E1000000', 0xF67364), (ALLOC, 'BA00010000', 0xF679CE), (CLEAR, '41B800010000', 0xF67A12)]
SKIP = 0xF67364 + 0xE1  # the search's jne
assert SKIP == 0xF67445

# HellForge leaves the three alone and has its restart step where the chain expects it
diag = open(os.path.join(stock_dir, 'difficulty_diag.c')).read()
assert re.search(r'kRestartSites\[4\] = \{0xF67FDBu,', diag) and '#define DIF_UNREACHABLE_GO_ON 0xF67FB7u' in diag
for path in glob.glob(os.path.join(stock_dir, '*.c')) + glob.glob(os.path.join(stock_dir, '*.h')):
    text = open(path, errors='replace').read().upper()
    for rva in (SEARCH, ALLOC, CLEAR, 0xF67224):
        assert '%X' % rva not in text, (path, hex(rva))

# what each pin proves, for the reconnect at the restart (rsp and rbp are the pass's; rbp = rsp + 0x100)
pins = [
    (0xF67224, '4C8BF9', 'the search: r15 = ctx, whose +0x18 is the level'),
    (0xF672C4, '488B410833C9488B6C2468488B6C2818', 'the search: rbp = the pocket cell\'s route cell ([subregion + 0x18])'),
    (0xF67349, 'E842F7FFFF84C00F84EF000000', 'the search: the neighbour inside the disk (0xF66A90), else 0xF67445'),
    (0xF679B0, '488B41104D8BE04C8B69084D8B701841B80800000048895598', 'the pass: r12 = ctx, r13 = the type objects, r14 = the level'),
    (0xF679CE, '448B088B41188945A4488B01488945A8488B413844894DA08B308B414089442474488B4130498B0C24488944247889742470E8CB3E7D0033D24889442468',
     'the pass: the route cells\' span at [rbp-0x60], the subregions\' at [rsp+0x70], the list from the arena (rdx bytes)'),
    (0xF67A12, '488BC8', 'the pass: the list cleared (r8 bytes)'),
    (0xF67A3C, '4C8BC348894590', 'the pass: [rbp-0x70] = the cells\' component ids'),
    (0xF67B2A, '440FB6582444895C2464', 'the pass: [rsp+0x64] = the planet\'s flag'),
    (0xF67B8E, '0F2875A00F29BC24900100000F287C2470', 'the pass: xmm6 = the route cells\' span, xmm7 = the subregions\''),
    (0xF67BA3, '488BC64C8975B8488945C0', 'the pass: [rbp-0x40] = the cell count'),
    (0xF67E4D, '660F7F7DA0660F7F742470E8B3F3FFFF',
     'before every search the spans change places: [rbp-0x58] = the subregions, [rsp+0x78] = the route cells'),
    (0xF67FB7, '8B442460488344246808FFC33BD87341448B5C24644C8B442468E93BFEFFFF498B4C2418',
     'the way on after a joined pocket (ebx the pocket, [rsp+0x60] the count), and rcx = the level at the restart'),
    (IN_DISK, '4C8B41080F57D24533C9418B402CF3480F2AD0F30F5915250046010F28DAF3410F5958504C8B42184983C008F30F59DB498B00',
     'the disk test (rcx ctx, rdx subregion): [ctx+8] the settings (+0x2C, +0x50), [subregion+0x18] + 8 the routes'),
]
for rva, hexes, _ in pins + [(s, h, 0) for s, h, _ in sites]:
    b = bytes.fromhex(hexes)
    assert game[rva:rva + len(b)] == b, hex(rva)
assert game[RESTART:RESTART + 6] == bytes.fromhex('FF8154F90000')
# the written spans and the pins do not overlap, and no pin is longer than the reader's buffer
spans = sorted([(s, s + len(h) // 2) for s, h, _ in sites] + [(r, r + len(h) // 2) for r, h, _ in pins])
assert all(a[1] <= b[0] for a, b in zip(spans, spans[1:])) and max(len(h) // 2 for _, h, _ in pins) <= 64


def c_bytes(hexes): return ', '.join('0x%02X' % x for x in bytes.fromhex(hexes))


o = ['/* Generated by scripts/gen_pocket_sites.py from the game\'s image and HellForge\'s source; do not edit. Game build 25480438. */\n',
     '#ifndef CO_POCKET_SITES_H\n#define CO_POCKET_SITES_H\n\n#include <stdint.h>\n\n',
     '#define CO_POCKET_SEARCH 0x%Xu\n#define CO_POCKET_SEARCH_GO 0x%Xu\n#define CO_POCKET_SEARCH_SKIP 0x%Xu\n' % (SEARCH, sites[0][2], SKIP),
     '#define CO_POCKET_ALLOC 0x%Xu\n#define CO_POCKET_CLEAR 0x%Xu\n#define CO_POCKET_RESTART 0x%Xu\n#define CO_POCKET_GO_ON 0x%Xu\n#define CO_POCKET_IN_DISK 0x%Xu\n'
     % (ALLOC, CLEAR, RESTART, GO_ON, IN_DISK),
     '/* The component list\'s bytes, 8 a component: the game\'s 32 components, and 512 on a complex level. */\n',
     '#define CO_POCKET_LIST_GAME 0x100u\n#define CO_POCKET_LIST_COMPLEX 0x1000u\n\n',
     '/* The sites the mod writes: the game\'s bytes, which no step of HellForge\'s changes, and the way on. */\n',
     'typedef struct CoPocketSite { uint32_t rva; uint8_t length; uint8_t bytes[14]; uint32_t on; } CoPocketSite;\n',
     'static const CoPocketSite kCoPocketSites[3] = {\n']
for rva, hexes, on in sites: o.append('    {0x%Xu, %d, {%s}, 0x%Xu},\n' % (rva, len(hexes) // 2, c_bytes(hexes), on))
o.append('};\n\n/* The game\'s code the stubs and the reconnect rely on, read only. */\n')
o.append('typedef struct CoPocketPin { uint32_t rva; uint8_t length; uint8_t bytes[64]; } CoPocketPin;\n')
o.append('static const CoPocketPin kCoPocketPins[%d] = {\n' % len(pins))
for rva, hexes, what in pins: o.append('    /* %s */\n    {0x%Xu, %d, {%s}},\n' % (what, rva, len(hexes) // 2, c_bytes(hexes)))
o.append('};\n\n#endif\n')
open(out, 'w').write(''.join(o))
print('%d written sites, %d pins' % (len(sites), len(pins)))
