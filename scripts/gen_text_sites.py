#!/usr/bin/env python3
# Writes src/xl/co_text_sites.h: the engine's text lookup, which the HUD's changing row titles are answered from
# (game build 25480438):
#   scripts/gen_text_sites.py <game.dll image dump> <helldivers2.exe image dump> <HellForge native/mod-loader> [out]
# The way from the engine API's text slot (the one HellForge's registry.c points at its own function) to the lookup is
# followed on the two dumps; HellForge's slot is read from its source.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game, exe = open(sys.argv[1], 'rb').read(), open(sys.argv[2], 'rb').read()
registry = open(os.path.join(sys.argv[3], 'registry.c')).read()
out = sys.argv[4] if len(sys.argv) > 4 else HERE + '/../src/xl/co_text_sites.h'


def hexes(b): return ', '.join('0x%02X' % x for x in b)


# HellForge: api = [game + REG_ENGINE_API], table = [api + 0x10], the text function at table + 1000; it keeps the one it
# finds there as the engine's and calls it for every id that is not a mod's text.
api_at = int(re.search(r'#define REG_ENGINE_API (0x[0-9A-Fa-f]+)u', registry).group(1), 16)
assert 'SafeRead(g_game + REG_ENGINE_API, &api, 8)' in registry and 'SafeRead(api + 0x10, &table, 8)' in registry
assert 'SafeRead(table + 1000, &current, 8)' in registry and 'ApiWrite(table + 1000, &detour, 8)' in registry
assert 'return g_engineText != NULL ? g_engineText(id, a, b, c) : "";' in registry
assert 'if (current < exe || current >= exe + exeSize)' in registry # it takes only an engine function for the engine's

base = struct.unpack_from('<Q', exe, struct.unpack_from('<I', exe, 0x3C)[0] + 0x30)[0]
api = struct.unpack_from('<Q', game, api_at)[0] - base
assert 0 < api < len(exe)
table = struct.unpack_from('<Q', exe, api + 0x10)[0] - base
assert 0 < table < len(exe)
ENTRY = struct.unpack_from('<Q', exe, table + 1000)[0] - base
# the slot's function: xor edx, edx (no language named); jmp the lookup
entry = exe[ENTRY:ENTRY + 7]
assert entry[:3] == bytes.fromhex('33D2E9')
LOOKUP = ENTRY + 7 + struct.unpack_from('<i', entry, 3)[0]
# the lookup (ecx the id, rdx a language's name or 0): saves rbx, rbp, rsi, pushes rdi, r12..r15, keeps rdx and ecx
pin = bytes.fromhex('48895C2408' '48896C2410' '4889742418' '57' '4154' '4155' '4156' '4157' '4883EC20')
assert exe[LOOKUP:LOOKUP + len(pin)] == pin
assert exe[LOOKUP + 0x25:LOOKUP + 0x2A] == bytes.fromhex('488BDA' '8BF9') # mov rbx, rdx; mov edi, ecx: its two arguments
# nothing else calls or jumps to it
callers = []
for op in (0xE8, 0xE9):
    i = exe.find(bytes([op]), 0x1000, 0x1400000)
    while i != -1:
        if i + 5 + struct.unpack_from('<i', exe, i + 1)[0] == LOOKUP: callers.append(i)
        i = exe.find(bytes([op]), i + 1, 0x1400000)
assert callers == [ENTRY + 2], callers
# an id it has no text for: the empty string (lea rax, [rip -> ""] before the epilogue)
miss = LOOKUP + 0x132
assert exe[miss:miss + 3] == bytes.fromhex('488D05')
empty = miss + 7 + struct.unpack_from('<i', exe, miss + 3)[0]
assert exe[empty] == 0

o = ['/* Generated by scripts/gen_text_sites.py from the engine\'s image and HellForge\'s source; do not edit. Game build 25480438. */\n',
     '#ifndef CO_TEXT_SITES_H\n#define CO_TEXT_SITES_H\n\n#include <stdint.h>\n\n',
     '/* In helldivers2.exe. The engine API\'s text function (the slot HellForge points at its own, which calls this one\n',
     ' * for every id that is not a mod\'s): xor edx, edx; jmp the lookup. */\n',
     '#define CO_TEXT_ENTRY 0x%Xu\nstatic const uint8_t kCoTextEntry[7] = {%s};\n' % (ENTRY, hexes(entry)),
     '/* The lookup (ecx a text id, rdx a language\'s name or 0): the text, or "" for an id it has none for. */\n',
     '#define CO_TEXT_LOOKUP 0x%Xu\nstatic const uint8_t kCoTextLookup[%d] = {%s};\n\n#endif\n' % (LOOKUP, len(pin), hexes(pin))]
open(out, 'w').write(''.join(o))
