#!/usr/bin/env python3
# Writes src/xl/co_beside_sites.h: the instructions the extra large world pins or writes where HellForge's level 11 has
# a step of its own, with what HellForge leaves there (game build 25480438):
#   scripts/gen_beside_sites.py <game.dll image dump> <HellForge native/mod-loader> [out]
# HellForge's sites, pins and stubs are read from its source; the game's bytes are checked against the dump.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game = open(sys.argv[1], 'rb').read()
stock = sys.argv[2]
out = sys.argv[3] if len(sys.argv) > 3 else HERE + '/../src/xl/co_beside_sites.h'


def src(name): return open(os.path.join(stock, name)).read()


def array(text, name):
    m = re.search(r'static const uint8_t ' + name + r'\[(\d*)\] = \{(.*?)\};', text, re.S)
    assert m, name
    body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
    b = bytes(int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]{2}|\b0\b', body))
    assert not m.group(1) or len(b) == int(m.group(1)), name
    return b


def define(text, name): return int(re.search(r'#define ' + name + r' (0x[0-9A-Fa-f]+)u', text).group(1), 16)


def hexes(b): return ', '.join('0x%02X' % x for x in b)


towns, streets, missions = src('difficulty_towns.c'), src('difficulty_streets.c'), src('difficulty_missions.c')

# The jumps HellForge writes inside instructions the prototype's city gates pin: E9 rel32, 0x90 to the length.
jumps = []
for text, table, count in ((towns, 'kTownBorderSites', 5), (streets, 'kStreetBorderSites', 4)):
    body = re.search(table + r'\[%d\] = \{(.*?)\};' % count, text, re.S).group(1)
    rows = re.findall(r'\{(0x[0-9A-F]+)u, (\d), \{([^}]*)\}, \{[^}]*\}, (0x[0-9A-F]+)u\}', body)
    assert len(rows) == count, table
    for site, length, pin, back in rows:
        site, length, back = int(site, 16), int(length), int(back, 16)
        pin = bytes(int(x, 0) for x in pin.split(','))[:length]
        assert back == site + length and game[site:site + length] == pin, hex(site)
        jumps.append((site, length))
body = re.search(r'kTownRefusals\[2\] = \{(.*?)\};', towns, re.S).group(1)
rows = re.findall(r'\{(0x[0-9A-F]+)u, \{([^}]*)\}, (0x[0-9A-F]+)u, \d\}', body)
assert len(rows) == 2
for site, pin, target in rows:
    site = int(site, 16)
    pin = bytes(int(x, 0) for x in pin.split(','))
    assert len(pin) == 6 and game[site:site + 6] == pin
    jumps.append((site, 6))
# every one is written as a jump of its whole length (InstallTowns' and InstallStreets' loops)
assert 'uint8_t jump[8] = {0xE9, 0, 0, 0, 0, 0x90, 0x90, 0x90};' in towns and 'ApiWrite(game + sites[i].site, jump, sites[i].length)' in towns
assert re.search(r'0xE9, 0, 0, 0, 0, 0x90', streets)
jumps.sort()

# The subregion stamps' merge (op 0x2B): HellForge's jump of 7 bytes and its stub.
merge_site, merge_drop = define(towns, 'DIF_TOWN_MERGE'), define(towns, 'DIF_TOWN_MERGE_DROP')
merge_pin = array(towns, 'kTownMergePin')
merge_head = array(towns, 'merge')
assert merge_site == 0xF35030 and game[merge_site:merge_site + 7] == merge_pin and len(merge_head) == 17
for line in ('memcpy(p, merge, sizeof merge); p += sizeof merge;', 'p = TownCount(p, 3);', 'p = TownJump(p, game + DIF_TOWN_MERGE_DROP);',
             'memcpy(p, kTownMergePin, 7); p += 7;', 'p = TownJump(p, game + DIF_TOWN_MERGE + 7);', '{DIF_TOWN_MERGE, 7}'):
    assert line in towns, line
assert '*p++ = 0xF0; *p++ = 0xFF; *p++ = 0x05;' in towns and "*p++ = 0xE9; return TownRel32(p, target);" in towns

# The destruction records' inlined store: HellForge's jump of 7 bytes at the store, its stub skipping a null slot.
store_site = define(towns, 'DIF_RECORD_STORE')
store_pin = array(towns, 'kRecordStorePin')
assert store_site == 0x13E036A and game[store_site:store_site + 7] == store_pin
for line in ('*p++ = 0x4D; *p++ = 0x85; *p++ = 0xC0; *p++ = 0x74; *p++ = 0x0C;', 'memcpy(p, kRecordStorePin, 7); p += 7;',
             'p = TownJump(p, game + DIF_RECORD_STORE + 7);', '{DIF_RECORD_STORE, 7}'):
    assert line in towns, line

# The director's mine list: HellForge's jump of 6 bytes and its stub with the list's 512 places.
mine_site, mine_add, mine_done = define(missions, 'DIF_MINE_SITE'), define(missions, 'DIF_MINE_ADD'), define(missions, 'DIF_MINE_DONE')
mine_pin, mine_stub = array(missions, 'kMinePin'), array(missions, 'kMineStub')
assert mine_site == 0xAD36A3 and game[mine_site:mine_site + 6] == mine_pin and mine_add == mine_site + 6
assert mine_stub[:6] == mine_pin and mine_stub[6] == 0x3D and struct.unpack('<I', mine_stub[7:11])[0] == 512
for line in ('memcpy(stub + 14, &rel, 4);', 'memcpy(stub + 26, &rel, 4);', 'uint8_t mines[6] = {0xE9, 0, 0, 0, 0, 0x90};'):
    assert line in missions, line

o = ['/* Generated by scripts/gen_beside_sites.py from HellForge\'s source and the game\'s image; do not edit. Game build 25480438. */\n',
     '#ifndef CO_BESIDE_SITES_H\n#define CO_BESIDE_SITES_H\n\n#include <stdint.h>\n\n',
     '/* HellForge\'s jumps inside the instructions the city gates pin: site, length (E9 rel32, then 0x90). */\n',
     '#define CO_BESIDE_JUMPS %du\n' % len(jumps),
     'static const struct { uint32_t site; uint8_t length; } kCoBesideJumps[CO_BESIDE_JUMPS] = {\n    ',
     ', '.join('{0x%Xu, %d}' % j for j in jumps), '};\n\n',
     '/* The stamps\' merge: the two instructions HellForge\'s jump replaces, its stub\'s head, then lock inc (7), a jump to\n'
     ' * the drop, the two instructions and a jump back. */\n',
     '#define CO_BESIDE_MERGE 0x%Xu\n#define CO_BESIDE_MERGE_DROP 0x%Xu\n' % (merge_site, merge_drop),
     'static const uint8_t kCoBesideMergePin[7] = {%s};\n' % hexes(merge_pin),
     'static const uint8_t kCoBesideMergeHead[17] = {%s};\n\n' % hexes(merge_head),
     '/* The records\' store: the two stores, behind HellForge\'s test for a null slot. */\n',
     '#define CO_BESIDE_STORE 0x%Xu\n' % store_site,
     'static const uint8_t kCoBesideStorePin[7] = {%s};\n\n' % hexes(store_pin),
     '/* The mine list: the count\'s load, and HellForge\'s stub (its jumps at 14 and 26, its counter at 21). */\n',
     '#define CO_BESIDE_MINE 0x%Xu\n#define CO_BESIDE_MINE_DONE 0x%Xu\n' % (mine_site, mine_done),
     'static const uint8_t kCoBesideMinePin[6] = {%s};\n' % hexes(mine_pin),
     'static const uint8_t kCoBesideMineStub[30] = {%s};\n\n#endif\n' % hexes(mine_stub)]
open(out, 'w').write(''.join(o))
