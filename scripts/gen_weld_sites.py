#!/usr/bin/env python3
# Writes src/xl/co_weld_sites.h: the structured maps' vertex weld (0xFBBB20) as HellForge's level 11 leaves it and as a
# world of 16384 m needs it (game build 25480438):
#   scripts/gen_weld_sites.py <game.dll image dump> <HellForge native/mod-loader> [out]
# HellForge's eight pool values are read from its source; the game's bytes are checked on the dump.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game = open(sys.argv[1], 'rb').read()
cities = open(os.path.join(sys.argv[2], 'difficulty_cities.c')).read()
out = sys.argv[3] if len(sys.argv) > 3 else HERE + '/../src/xl/co_weld_sites.h'


def hexes(b): return ', '.join('0x%02X' % x for x in b)


body = re.search(r'kBucketPool\[8\] = \{(.*?)\};', cities, re.S).group(1)
rows = re.findall(r'\{(0x[0-9A-F]+)u, (\d), (\d), \{([^}]*)\}, (0x[0-9A-F]+)u\}', body)
assert len(rows) == 8
assert 'ApiWrite(game + kBucketPool[i].rva + kBucketPool[i].at, &kBucketPool[i].value, 4)' in cities
# A block: u32 count, PER vertices of 0x98 at +8, PER output pointers behind them. 576 blocks at +0xBA60, then the count.
PER, BLOCKS, POOL = 256, 576, 0xBA60
pointers = 8 + PER * 0x98
block = pointers + PER * 8
count = POOL + BLOCKS * block
assert 8 + 16 * 0x98 == 0x988 and 0x988 + 16 * 8 == 0xA08 and POOL + 512 * 0xA08 == 0x14CA60
pool = []
for rva, length, at, pin, value in rows:
    rva, length, at, value = int(rva, 16), int(length), int(at), int(value, 16)
    pin = bytes(int(x, 0) for x in pin.split(','))[:length]
    assert game[rva:rva + length] == pin and at + 4 == length, hex(rva)
    was = struct.unpack_from('<I', pin, at)[0]
    # what each value is, from the game's own: the allocation, the clear from +0x1248, the pool's clear, the count
    stock_count = POOL + BLOCKS * 0xA08
    kind = {0x14CA68: (stock_count + 8, count + 8), 0x14B820: (stock_count + 8 - 0x1248, count + 8 - 0x1248),
            0x141000: (BLOCKS * 0xA08, BLOCKS * block), 0x14CA60: (stock_count, count)}[was]
    assert value == kind[0], hex(rva)
    pool.append((rva, length, at, pin[:at] + struct.pack('<I', value), kind[1]))
strides = [(0xFB9B9A, bytes.fromhex('4869C9080A0000')), (0xFB9E88, bytes.fromhex('4869C9080A0000'))]
points = [(0xFBB080, bytes.fromhex('4B8B84D088090000')), (0xFBB0AF, bytes.fromhex('4B898CD088090000')), (0xFBB12F, bytes.fromhex('4B8B84D088090000'))]
# the three tests of a block's 16 places: site, bytes, where the branch leads, where the code goes on
full = [(0xFB9C19, bytes.fromhex('4183F810722E'), 0xFB9C4D, 0xFB9C1F), (0xFB9F9D, bytes.fromhex('4183F8100F8314010000'), 0xFBA0BB, 0xFB9FA7),
        (0xFBB074, bytes.fromhex('83FA100F83C0000000'), 0xFBB13D, 0xFBB07D)]
for rva, b in strides + points: assert game[rva:rva + len(b)] == b, hex(rva)
for rva, b, taken, on in full:
    assert game[rva:rva + len(b)] == b and on == rva + len(b), hex(rva)
    rel = b[5] if b[4] == 0x72 else struct.unpack_from('<i', b, len(b) - 4)[0]
    assert taken == on + rel, hex(rva)
assert game[0xFBAFF0:0xFBAFFB] == bytes.fromhex('F30F1091381200004C8BD1')

o = ['/* Generated by scripts/gen_weld_sites.py from HellForge\'s source and the game\'s image; do not edit. Game build 25480438. */\n',
     '#ifndef CO_WELD_SITES_H\n#define CO_WELD_SITES_H\n\n#include <stdint.h>\n\n',
     '/* A block of the pool at weld + 0xBA60: u32 count, the vertices of 0x98 at +8, their output pointers behind them. */\n',
     '#define CO_WELD_POOL 0x%Xu\n#define CO_WELD_BLOCKS %du\n#define CO_WELD_PER %du\n#define CO_WELD_POINTERS 0x%Xu\n#define CO_WELD_BLOCK 0x%Xu\n#define CO_WELD_COUNT 0x%Xu\n\n'
     % (POOL, BLOCKS, PER, pointers, block, count),
     '/* The pool\'s sizes and its count\'s place: the bytes HellForge leaves (576 blocks of 16) and the value for 576 of 256. */\n',
     'typedef struct CoWeldValue { uint32_t rva; uint8_t length, at; uint8_t stock[8]; uint32_t own; } CoWeldValue;\n',
     'static const CoWeldValue kCoWeldValues[13] = {\n']
for rva, length, at, stock, own in pool: o.append('    {0x%Xu, %d, %d, {%s}, 0x%Xu},\n' % (rva, length, at, hexes(stock), own))
o.append('    /* the game\'s own: a block\'s stride (imul rcx, rcx, 0xA08) and the pointers\' place in it ([r8+r10*8+0x988]) */\n')
for rva, b in strides: o.append('    {0x%Xu, 7, 3, {%s}, 0x%Xu},\n' % (rva, hexes(b), block))
for rva, b in points: o.append('    {0x%Xu, 8, 4, {%s}, 0x%Xu},\n' % (rva, hexes(b), pointers))
o.append('};\n\n/* The three tests of a block\'s 16 places (cmp r8d / r8d / edx, 0x10): the bytes, where the branch leads, the way on. */\n')
o.append('typedef struct CoWeldFull { uint32_t rva; uint8_t length; uint8_t bytes[10]; uint32_t taken, on; } CoWeldFull;\n')
o.append('static const CoWeldFull kCoWeldFull[3] = {\n')
for rva, b, taken, on in full: o.append('    {0x%Xu, %d, {%s}, 0x%Xu, 0x%Xu},\n' % (rva, len(b), hexes(b), taken, on))
o.append('};\n\n/* An edge endpoint\'s node, 0xFBAFF0 (rcx weld, rdx vertex, r8 nodes, r9 out). */\n')
o.append('#define CO_WELD_ENDPOINT 0xFBAFF0u\n#define CO_WELD_ENDPOINT_PIN "F3 0F 10 91 38 12 00 00 4C 8B D1"\n\n#endif\n')
open(out, 'w').write(''.join(o))
