#!/usr/bin/env python3
# Writes src/xl/co_nav_sites.h: HellForge's two navigation stubs and the game's and the engine's bytes around them
# (game build 25480438):
#   scripts/gen_nav_sites.py <game.dll image dump> <helldivers2.exe image dump> <HellForge native/mod-loader> [out]
# The stubs and pins are taken from HellForge's source by name (its STUB_ macros expanded) and checked against the dumps.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game = open(sys.argv[1], 'rb').read()
exe = open(sys.argv[2], 'rb').read()
stock = sys.argv[3]
out = sys.argv[4] if len(sys.argv) > 4 else HERE + '/../src/xl/co_nav_sites.h'

maps = open(os.path.join(stock, 'difficulty_maps.c')).read()
macros = {}
for path in sorted(os.listdir(stock)):
    if not path.endswith(('.c', '.h')): continue
    for name, body in re.findall(r'#define (STUB_[A-Z0-9_]+) ((?:.*\\\n)*.*)', open(os.path.join(stock, path)).read()):
        macros.setdefault(name, re.sub(r'/\*.*?\*/', '', body.replace('\\\n', ' '), flags=re.S))


def expand(text):
    for _ in range(4):
        for name in sorted(macros, key=len, reverse=True): text = re.sub(r'\b%s\b' % name, macros[name], text)
    return text


def array(name):
    found = re.search(r'static const uint8_t %s\[(\d+)\] = \{(.*?)\};' % name, maps, re.S)
    assert found, name
    items = [i.strip() for i in expand(re.sub(r'/\*.*?\*/', '', found.group(2), flags=re.S)).split(',') if i.strip()]
    values = bytes(int(i, 0) for i in items)
    assert len(values) == int(found.group(1)), (name, len(values))
    return values


def define(name): return int(re.search(r'#define %s (0x[0-9A-Fa-f]+)u' % name, maps).group(1), 16)


nav, ship, exe_pin = array('kNavPin'), array('kNavShipPin'), array('kNavExePin')
read, read256 = array('kNavTileSizeRead'), array('kNavTileSize256')
stub, ship_stub = array('kNavStub'), array('kNavShipStub')
site, back, ship_site, ship_back = define('DIF_NAV_SITE'), define('DIF_NAV_BACK'), define('DIF_NAV_SHIP_SITE'), define('DIF_NAV_SHIP_BACK')
system, worlds, count, pin_at, read_at = define('DIF_NAV_SYSTEM'), define('DIF_NAV_WORLDS'), define('DIF_NAV_COUNT'), define('DIF_NAV_PIN'), define('DIF_NAV_TILE_SIZE_READ')
assert (site, back, ship_site, ship_back) == (0xC17E2E, 0xC19E1C, 0xADA075, 0xADA07F)
assert game[site:site + 15] == nav and game[ship_site:ship_site + 10] == ship and exe[pin_at:pin_at + 23] == exe_pin and exe[read_at:read_at + 8] == read
# the two floats the tile size read is pointed at
at128 = read_at + 8 + struct.unpack('<i', read[4:])[0]
at256 = read_at + 8 + struct.unpack('<i', read256)[0]
assert struct.unpack('<f', exe[at128:at128 + 4])[0] == 128.0 and struct.unpack('<f', exe[at256:at256 + 4])[0] == 256.0
# the fills are zero in the source: the retile function, the nav system's address, the way back
assert stub[60:68] == bytes(8) and stub[126:134] == bytes(8) and stub[141:145] == bytes(4) and stub[140] == 0xE9
assert ship_stub[65:73] == bytes(8) and ship_stub[140:144] == bytes(4) and ship_stub[139] == 0xE9
# up to the call's return both stubs are "keep everything, call C with the id and the level, put everything back"
assert stub[54:58] == bytes([0x49, 0x8B, 0x57, 0x18]) and ship_stub[54:63] == bytes([0x41, 0x8B, 0x8E, 0xF0, 0x10, 0x00, 0x00, 0x31, 0xD2])


def hexes(b): return ', '.join('0x%02X' % x for x in b)


lines = ['/* Generated by scripts/gen_nav_sites.py from HellForge\'s source and the game\'s images; do not edit. Game build 25480438. */\n',
         '#ifndef CO_NAV_SITES_H\n#define CO_NAV_SITES_H\n\n',
         '#define CO_NAV_SITE 0x%Xu      /* op 0x68: the id in ecx, the pass in r15, its level at +0x18; 15 bytes */\n' % site,
         '#define CO_NAV_BACK 0x%Xu\n' % back,
         '#define CO_NAV_SHIP_SITE 0x%Xu /* the ship\'s set-up: the id at [r14+0x10F0]; 10 bytes */\n' % ship_site,
         '#define CO_NAV_SHIP_BACK 0x%Xu\n' % ship_back,
         '#define CO_NAV_SYSTEM 0x%Xu\n' % system,
         '#define CO_NAV_WORLDS 0x%Xu    /* exe: the nav world pointers, and their count */\n' % worlds,
         '#define CO_NAV_COUNT 0x%Xu\n' % count,
         '#define CO_NAV_EXE_PIN 0x%Xu     /* exe: the per-level set-up, a reader of both */\n' % pin_at,
         '#define CO_NAV_TILE_READ 0x%Xu   /* exe: the terrain build\'s tile size, movss xmm0, [rip+128.0] */\n' % read_at,
         '#define CO_NAV_TILE_128 0x%Xu   /* exe: the two floats HellForge points it at */\n' % at128,
         '#define CO_NAV_TILE_256 0x%Xu\n' % at256,
         'static const uint8_t kNavGame[15] = {%s};\n' % hexes(nav),
         'static const uint8_t kNavShipGame[10] = {%s};\n' % hexes(ship),
         'static const uint8_t kNavExe[23] = {%s};\n' % hexes(exe_pin),
         'static const uint8_t kNavTileRead[8] = {%s};\n' % hexes(read),
         'static const uint8_t kNavTileRead256[4] = {%s};\n' % hexes(read256),
         '/* HellForge\'s stubs: its retile function at +60 / +65, the nav system at +126, the way back at +141 / +140. */\n',
         'static const uint8_t kNavStock[145] = {%s};\n' % hexes(stub),
         'static const uint8_t kNavShipStock[144] = {%s};\n' % hexes(ship_stub),
         '\n#endif\n']
open(out, 'w').writelines(lines)
print('nav sites written')
