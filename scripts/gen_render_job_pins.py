#!/usr/bin/env python3
# Writes the render job free's pins from the helldivers2.exe image dump (game build 25480438):
#   scripts/gen_render_job_pins.py <helldivers2.exe image dump>
# src/xl/proto/living_world_render_pins.h: the pins as patterns of at most 48 bytes, for LwRenderJobPins.
# tests/co_render_job_bytes.h: the same ranges' bytes, which freecuts puts in its fake exe to test every pinned byte.
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
exe = open(sys.argv[1], 'rb').read()

# (first, end) RVAs, end exclusive, and what the free assumes there.
JOB = [
    (0x6FD1B0, 0x6FD1BC, 'the recording: the hooked prologue'),
    (0x6C9FF4, 0x6CA003, 'the update pass reads its own job context only'),
    (0x6CA0DF, 0x6CA0F6, 'the job: its argument J, J+0x70 the job context'),
    (0x6CA276, 0x6CA321, "the job: X's table set, the recording's arguments and call"),
    (0x6CA321, 0x6CA477, "the job's tail: X's barrier lists only, then the done flag and the return"),
    (0x6CBE0B, 0x6CBE62, 'the feeder: the recording jobs depend on the update jobs; only these are released'),
    (0x6CD171, 0x6CD2EC, 'the dispatch: J+0x70, the copy, the done flag cleared'),
    (0x6CD36F, 0x6CD376, 'the dispatch: the job function 0x6CA0C0'),
    (0x6CD3E4, 0x6CD3F6, "the dispatch: the update pass's data holds the job context"),
    (0x6CD422, 0x6CD429, 'the dispatch: the update pass 0x6C9FD0'),
    (0x6CD5C5, 0x6CD654, 'the dispatch: the wait on each done flag, then the copy emptied'),
]
# The version copies' own pins (LwRenderCopiesPins), as long as their patterns: the test only.
COPIES = [(0x6D55E0, 20), (0x6CD17C, 22), (0x6CD637, 20), (0x6CC700, 19), (0x6CC87B, 19), (0x6CC8BE, 7), (0x6D5560, 17),
          (0x6CD5F7, 5), (0x6E2230, 10)]
CHUNK = 48


def hexes(first, end):
    return ' '.join('%02X' % b for b in exe[first:end])


src = ['/* Generated by scripts/gen_render_job_pins.py from the helldivers2.exe image (build 25480438); do not edit. */',
       'static const struct { uint32_t rva; const char* hex; } kLwJobPins[] = {']
for first, end, what in JOB:
    src.append('    /* %s */' % what)
    for at in range(first, end, CHUNK):
        src.append('    {0x%06Xu, "%s"},' % (at, hexes(at, min(at + CHUNK, end))))
src.append('};')
open(HERE + '/../src/xl/proto/living_world_render_pins.h', 'w').write('\n'.join(src) + '\n')

test = ['/* Generated by scripts/gen_render_job_pins.py from the helldivers2.exe image (build 25480438); do not edit.',
        ' * The bytes each render job pin covers, as the game has them. */',
        'static const struct { uint32_t rva, size; const uint8_t* bytes; } kRenderJobBytes[] = {']
for first, end, what in JOB:
    test.append('    {0x%06Xu, %d, (const uint8_t[]){%s}},' % (first, end - first, ', '.join('0x%02X' % b for b in exe[first:end])))
test.append('};')
test.append('static const struct { uint32_t rva, size; const uint8_t* bytes; } kRenderCopiesBytes[] = {')
for first, size in COPIES:
    test.append('    {0x%06Xu, %d, (const uint8_t[]){%s}},' % (first, size, ', '.join('0x%02X' % b for b in exe[first:first + size])))
test.append('};')
open(HERE + '/../tests/co_render_job_bytes.h', 'w').write('\n'.join(test) + '\n')
