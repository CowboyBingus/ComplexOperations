#!/usr/bin/env python3
# Writes the stranded-span rescue's pins from the helldivers2.exe image dump (game build 25480438):
#   scripts/gen_span_rescue_pins.py <helldivers2.exe image dump>
# src/xl/proto/xl_span_rescue_pins.h: the pins as patterns of at most 48 bytes, for SrPins.
# tests/co_rpmalloc_bytes.h: the same ranges' bytes, rpmalloc's allocation entry and its size class table, which
# spanrescue puts in its fake exe to run the game's own allocator code against the rescue.
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
exe = open(sys.argv[1], 'rb').read()

# (first, end) RVAs, end exclusive, and what the rescue assumes there.
PINS = [
    (0x667850, 0x66786A, 'the default span map: its prologue (no caller but the config pointer)'),
    (0x667920, 0x66793B, 'the default span unmap: address, size, offset, release'),
    (0x6677B9, 0x6677BF, 'span map call through [0x27B8C60]'),
    (0x667AD2, 0x667AD8, 'span map call through [0x27B8C60]'),
    (0x667BE2, 0x667BE8, 'span map call through [0x27B8C60]'),
    (0x668F51, 0x668F57, 'span map call through [0x27B8C60]'),
    (0x669172, 0x669178, 'span map call through [0x27B8C60]'),
    (0x669C62, 0x669C68, 'span map call through [0x27B8C60]'),
    (0x669FC1, 0x669FC7, 'span map call through [0x27B8C60]'),
    (0x667847, 0x66784E, 'span unmap jump through [0x27B8C68]'),
    (0x667CD9, 0x667CDF, 'span unmap call through [0x27B8C68]'),
    (0x667D74, 0x667D7B, 'span unmap jump through [0x27B8C68]'),
    (0x66A097, 0x66A09D, 'span unmap call through [0x27B8C68]'),
    (0x66A5DE, 0x66A5E4, 'span unmap call through [0x27B8C68]'),
    (0x66AFFF, 0x66B005, 'span unmap call through [0x27B8C68]'),
    (0x66AA9E, 0x66AAE4, 'init: the defaults stored in the config pointers, then the initialised flag'),
    (0x6697E0, 0x669A42, 'the allocation fallback: partial list pop, deferred list taken, a new span set up heap first'),
    (0x66A140, 0x66A22A, "the owner's free: a full span to the partial list head"),
    (0x66A230, 0x66A266, 'a span whose blocks all came back deferred goes to the owner heap +0x710'),
    (0x66A280, 0x66A2E6, "another thread's free: the span's deferred list under its -1 lock"),
    (0x66A2F0, 0x66A4AA, 'the small and medium free: owner test, deferred and direct paths'),
    (0x667F80, 0x667FA6, "the span's deferred list taken (the extract)"),
    (0x667FB0, 0x667FC7, 'a span is full: no free list and every block handed out'),
    (0x6302F0, 0x63031B, "the trim: the hooked prologue and the caller's heap at [[gs:0x58]]+0x4350"),
    (0x3245FF, 0x324640, "trim-all: the pool [[0x1A10208]+0x318]'s workers +0x90 / +0x88 get +0x7D"),
    (0x6253BF, 0x6253D2, 'a pool worker trims its own heap after its jobs when +0x7D is set'),
]
# rpmalloc's allocation entries the test runs beside the pinned code (not pins).
EXEC = [
    (0x669AB0, 0x669B25, 'medium allocation entry (heap, size)'),
]
CHUNK = 48


def hexes(first, end):
    return ' '.join('%02X' % b for b in exe[first:end])


def cbytes(first, end):
    return ', '.join('0x%02X' % b for b in exe[first:end])


src = ['/* Generated by scripts/gen_span_rescue_pins.py from the helldivers2.exe image (build 25480438); do not edit. */',
       'static const struct { uint32_t rva; const char* hex; } kSrPins[] = {']
for first, end, what in PINS:
    src.append('    /* %s */' % what)
    for at in range(first, end, CHUNK):
        src.append('    {0x%06Xu, "%s"},' % (at, hexes(at, min(at + CHUNK, end))))
src.append('};')
open(os.path.join(HERE, '..', 'src', 'xl', 'proto', 'xl_span_rescue_pins.h'), 'w').write('\n'.join(src) + '\n')

test = ['/* Generated by scripts/gen_span_rescue_pins.py from the helldivers2.exe image (build 25480438); do not edit.',
        ' * The code each span rescue pin covers and the medium allocation entry, as the game has them; the size class table',
        ' * and page size as rpmalloc set them up. */',
        'static const struct { uint32_t rva, size; const uint8_t* bytes; } kRpmallocBytes[] = {']
for first, end, what in PINS + EXEC:
    test.append('    {0x%06Xu, %d, (const uint8_t[]){%s}},' % (first, end - first, cbytes(first, end)))
test.append('};')
test.append('static const uint8_t kRpmallocSizes[96 * 8] = {%s};' % cbytes(0x27B0DF0, 0x27B0DF0 + 96 * 8))
test.append('static const uint8_t kRpmallocPage[8] = {%s};' % cbytes(0x27B10F0, 0x27B10F8))
open(os.path.join(HERE, '..', 'tests', 'co_rpmalloc_bytes.h'), 'w').write('\n'.join(test) + '\n')
