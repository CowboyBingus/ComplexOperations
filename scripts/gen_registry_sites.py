#!/usr/bin/env python3
# Writes src/co_registry_sites.h: the loads that lead the game to the registry's list of loadout card widgets (game
# build 25480438), from scripts/sites/registry_sites.py and a dump of the game's code:
#   scripts/gen_registry_sites.py <game.dll image dump> [out]
# Each row is a `mov r64,[rip+disp32]` of the registry's global; the mod rewrites its disp32 to read a qword of its own.
# Every row is checked against the dump here, and again by the mod against the running game before it writes. No byte
# may be shared with a site, cave or stub of the mod's other steps.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE + '/sites')
import registry_sites as R

REGS = ['rax', 'rcx', 'rdx', 'rbx', 'rsp', 'rbp', 'rsi', 'rdi', 'r8', 'r9', 'r10', 'r11', 'r12', 'r13', 'r14', 'r15']
dump = open(sys.argv[1], 'rb').read()
out = sys.argv[2] if len(sys.argv) > 2 else HERE + '/../src/co_registry_sites.h'

sites = []
for rva, old, reg, _ in R.SITES:
    b = bytes.fromhex(old)
    assert len(b) == 7 and dump[rva:rva + 7] == b, hex(rva)
    # REX.W (R for r8..r15), 8B, mod 00 and r/m 101: rip-relative; the load must reach the global.
    assert b[0] in (0x48, 0x4C) and b[1] == 0x8B and b[2] & 0xC7 == 0x05, hex(rva)
    assert REGS[(b[0] >> 2 & 1) << 3 | b[2] >> 3 & 7] == reg, hex(rva)
    assert rva + 7 + struct.unpack_from('<i', b, 3)[0] == R.GLOBAL, hex(rva)
    sites.append((rva, b))


def rows(name, part, end=None):
    """The leading numbers of each row of a table in a generated header."""
    text = open(HERE + '/../src/' + name).read()
    text = text[text.index(part):]
    if end: text = text[:text.index(end)]
    found = []
    for line in re.findall(r'^    \{(0x[0-9A-F]+u[^{]*)', text, re.M):
        found.append(tuple(int(x.strip().rstrip('u'), 0) for x in line.split(',') if re.fullmatch(r'\s*(0x[0-9A-F]+u?|\d+)\s*', x)))
    return found


# Every byte the other steps write, in any build.
taken = []
stubs = [(r[0], r[1]) for r in rows('co_session_sites.h', 'kCoSessionStubs')]
taken += [(rva, rva + size) for rva, size in stubs]
taken += [(r[0] + r[1], r[0] + r[1] + 4) for r in rows('co_session_sites.h', 'kCoSessionSites', 'kCoSessionStubs') if r[:2] not in stubs]
taken += [(r[0] + r[1], r[0] + r[1] + 4) for r in rows('co_manager_sites.h', 'kCoManagerSites', 'kCoManagerCaves')]
taken += [(r[0], max(r[0] + r[1], r[2])) for r in rows('co_manager_sites.h', 'kCoManagerCaves')]
taken += [(r[0] + r[1], r[0] + r[1] + 4) for r in rows('co_pod_sites.h', 'kCoPodSites')]
taken += [(r[0], r[0] + r[1]) for r in rows('co_count_sites.h', 'kCoCountSites', 'kCoCountClears')]
taken += [(r[0], r[0] + 8) for r in rows('co_count_sites.h', 'kCoCountClears', 'kCoCountCode')]
taken += [(r[0], r[0] + r[1]) for r in rows('co_count_sites.h', 'kCoCountCaves', 'kCoMessageShapes')]
taken += [(r[0], r[0] + r[1]) for r in rows('co_ui_sites.h', 'kCoUiSites', 'kCoUiCode')]
assert len(taken) > 2500, len(taken)
for rva, b in sites:
    assert all(rva + len(b) <= c or d <= rva for c, d in taken), hex(rva)

h = ['/* Generated by scripts/gen_registry_sites.py from scripts/sites/registry_sites.py; do not edit. Game build 25480438. */\n',
     '#ifndef CO_REGISTRY_SITES_H\n#define CO_REGISTRY_SITES_H\n\n',
     '#define CO_REGISTRY_GLOBAL 0x%Xu\n' % R.GLOBAL,
     '/* The card widgets\' list in the registry: a count, then entries of %d bytes from +8. */\n' % R.ENTRY,
     '#define CO_CARD_LIST 0x%Xu\n#define CO_CARD_ENTRY %du\n#define CO_CARD_ROOM_GAME %du\n#define CO_CARD_ROOM %du\n\n'
     % (R.LIST, R.ENTRY, R.ROOM_GAME, R.ROOM),
     '/* {rva, size, where the disp32 is, the game\'s bytes} */\nstatic const CoRegistrySite kCoRegistrySites[] = {\n']
for (rva, b), (_, _, reg, note) in zip(sites, R.SITES):
    h.append('    {0x%Xu, %d, 3, {%s}},  /* %s: %s */\n' % (rva, len(b), ', '.join('0x%02X' % x for x in b), reg, note))
h.append('};\n\n#endif\n')
open(out, 'w').writelines(h)
print('%d sites; no overlap with %d sites of the other steps' % (len(sites), len(taken)))
