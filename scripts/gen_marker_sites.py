#!/usr/bin/env python3
# Writes src/xl/co_marker_sites.h: the tactical map's objective markers as the game and HellForge's level 11 leave them
# (game build 25480438): the map object's own 16 slots and 10 trackers, and HellForge's two guards of the 17th slot.
#   scripts/gen_marker_sites.py <game.dll image dump> <HellForge native/mod-loader> [out]
# HellForge's sites, pins and limit are read from its source; the game's bytes are checked on the dump.
import os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
game = open(sys.argv[1], 'rb').read()
missions = open(os.path.join(sys.argv[2], 'difficulty_missions.c')).read()
out = sys.argv[3] if len(sys.argv) > 3 else HERE + '/../src/xl/co_marker_sites.h'


def hexes(b): return ', '.join('0x%02X' % x for x in b)


def define(name): return int(re.search(r'#define %s (0x[0-9A-F]+|\d+)u' % name, missions).group(1), 0)


def pin(name):
    length, body = re.search(r'%s\[(\d)\] = \{([^}]*)\}' % name, missions).groups()
    b = bytes(int(x, 0) for x in body.split(','))
    assert len(b) == int(length)
    return b


# The map object (HUD + 0x1A0E28): the slots, their ids and the trackers lie back to back, so a 17th slot is the ids
# and the first tracker. Its builder 0x18A5580 makes 16 and 10; the updater 0x18B42F0 leaves each pass at 16 or 10.
SLOTS, TRACKERS = 16, 10
assert 0xF958 + SLOTS * 0x2B8 == 0x124D8 and 0x124D8 + SLOTS * 4 == 0x12518 and 0x12518 + TRACKERS * 0x158 == 0x13288
assert define('DIF_MARKER_SLOTS') == SLOTS
limits = [(0x18A60D7, '41B810000000', 2, SLOTS, 'the builder: mov r8d, 16 slots'),
          (0x18A6195, '41B80A000000', 2, TRACKERS, 'the builder: mov r8d, 10 trackers'),
          (0x18B44A3, '83FB10', 2, SLOTS, 'the instance pass, before each instance: cmp ebx, 16'),
          (0x18B44AC, '83FF0A', 2, TRACKERS, 'cmp edi, 10'),
          (0x18B5322, '837C244010', 4, SLOTS, 'the entity pass, before each instance of an entity: cmp [rsp+0x40], 16'),
          (0x18B532D, '837C246C0A', 4, TRACKERS, 'cmp [rsp+0x6c], 10')]
for rva, b, at, value, _ in limits:
    b = bytes.fromhex(b)
    assert game[rva:rva + len(b)] == b and b[at] == value, hex(rva)
# both instance tests leave the pass (jae 0x18B516C), the entity tests the entity's instances (jae 0x18B54AC)
for rva, n, target in ((0x18B44A6, 6, 0x18B516C), (0x18B44AF, 6, 0x18B516C), (0x18B5327, 6, 0x18B54AC), (0x18B5332, 6, 0x18B54AC)):
    assert game[rva:rva + 2] == b'\x0F\x83' and rva + n + struct.unpack_from('<i', game, rva + 2)[0] == target, hex(rva)
# the updater takes the counts of its last run from +0xF94C / +0xF948 and stores this run's there (it hides what is between)
assert game[0x18B4317:0x18B431D] == bytes.fromhex('8B814CF90000') and game[0x18B4326:0x18B432C] == bytes.fromhex('8B8148F90000')
assert game[0x18B5FB7:0x18B5FBF] == bytes.fromhex('4589B4244CF90000') and game[0x18B5FC7:0x18B5FCF] == bytes.fromhex('4589BC2448F90000')

# HellForge's guards: the entity pass's loop head and the route marker, each "cmp [rsp+0x40], 16; jae leave; the site's
# own instructions; jmp back" behind a jump padded with nops (PrepareMarkerStubs, JumpToMarkerStubs).
for form in ('stub[0] = 0x83; stub[1] = 0x7C; stub[2] = 0x24; stub[3] = 0x40; stub[4] = (uint8_t)DIF_MARKER_SLOTS;', 'stub[5] = 0x0F; stub[6] = 0x83;',
             'rel = (int32_t)(game + guards[i].leave - (uintptr_t)(stub + 11)); memcpy(stub + 7, &rel, 4);', 'memcpy(stub + 11, guards[i].pin, n);',
             'stub[11 + n] = 0xE9;', 'rel = (int32_t)(game + guards[i].site + n - (uintptr_t)(stub + 16 + n)); memcpy(stub + 12 + n, &rel, 4);',
             '{DIF_MARKER_LOOP_SITE, kMarkerLoopPin, 8, DIF_MARKER_LOOP_EXIT}, {DIF_MARKER_ROUTE_SITE, kMarkerRoutePin, 6, DIF_MARKER_ROUTE_SKIP}',
             'memset(jump, 0x90, sizeof jump);', 'if (ApiWrite(d->game + markerSites[i], jump, markerLengths[i]))'):
    assert form in missions, form
guards = [(define('DIF_MARKER_LOOP_SITE'), pin('kMarkerLoopPin'), define('DIF_MARKER_LOOP_EXIT')),
          (define('DIF_MARKER_ROUTE_SITE'), pin('kMarkerRoutePin'), define('DIF_MARKER_ROUTE_SKIP'))]
assert [(g[0], len(g[1]), g[2]) for g in guards] == [(0x18B51B0, 8, 0x18B5A17), (0x18B5FF4, 6, 0x18B5E22)]
for rva, b, leave in guards: assert game[rva:rva + len(b)] == b, hex(rva)
# the loop's exit is where the game's own loop ends, the route's skip where the path without a route marker goes on
assert game[0x18B5A11:0x18B5A17] == b'\x0F\x82' + struct.pack('<i', 0x18B51B0 - 0x18B5A17)
assert game[0x18B5A45:0x18B5A4B] == b'\x0F\x86' + struct.pack('<i', 0x18B5E22 - 0x18B5A4B)

o = ['/* Generated by scripts/gen_marker_sites.py from HellForge\'s source and the game\'s image; do not edit. Game build 25480438. */\n',
     '#ifndef CO_MARKER_SITES_H\n#define CO_MARKER_SITES_H\n\n#include <stdint.h>\n\n',
     '/* The map object\'s own arrays: its marker slots (+0xF958, 0x2B8 each) and its trackers (+0x12518, 0x158 each). */\n',
     '#define CO_MARKER_SLOTS %du\n#define CO_MARKER_TRACKERS %du\n\n' % (SLOTS, TRACKERS),
     '/* Where the game\'s builder (0x18A5580) and updater (0x18B42F0) hold those two counts; `at` is the count\'s byte. */\n',
     'typedef struct CoMarkerLimit { uint32_t rva; uint8_t length, at; uint8_t bytes[6]; } CoMarkerLimit;\n',
     'static const CoMarkerLimit kCoMarkerLimits[%d] = {\n' % len(limits)]
for rva, b, at, value, what in limits: o.append('    {0x%Xu, %d, %d, {%s}}, /* %s */\n' % (rva, len(b) // 2, at, hexes(bytes.fromhex(b)), what))
o.append('};\n\n/* HellForge\'s guards of a 17th slot: the site\'s own bytes, which its stub runs behind "cmp [rsp+0x40], 16; jae leave". */\n')
o.append('typedef struct CoMarkerGuard { uint32_t rva; uint8_t length; uint8_t game[8]; uint32_t leave; } CoMarkerGuard;\n')
o.append('static const CoMarkerGuard kCoMarkerGuards[%d] = {\n' % len(guards))
for (rva, b, leave), what in zip(guards, ('the entity pass\'s loop head', 'the route marker')):
    o.append('    {0x%Xu, %d, {%s}, 0x%Xu}, /* %s */\n' % (rva, len(b), hexes(b), leave, what))
o.append('};\n\n#endif\n')
open(out, 'w').write(''.join(o))
